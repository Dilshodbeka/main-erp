import { readFileSync } from 'node:fs';
import { build } from 'esbuild';
import { describe, expect, it } from 'vitest';
import { emptyState } from './domain';
import { OWNER_COMMANDS } from './telegram-reports';
import { ownerKeyboard, ownerNeedsState, ownerReply, parseOwnerIds, resolveOwnerInput } from './telegram-owner';

describe('owner bot', () => {
  it('accepts only numeric Telegram ids', () => {
    expect(parseOwnerIds('7135485514, 42x; 123456')).toEqual(['7135485514', '123456']);
    expect(parseOwnerIds(undefined)).toEqual([]);
  });

  it('resolves slash commands and tapped keyboard labels', () => {
    for (const row of OWNER_COMMANDS) {
      expect(resolveOwnerInput(row.command)).toBe(row.key);
      expect(resolveOwnerInput(row.label)).toBe(row.key);
    }
    expect(resolveOwnerInput('/start')).toBe('menu');
    expect(resolveOwnerInput('salom')).toBeNull();
  });

  it('answers the menu without ERP data', () => {
    expect(ownerNeedsState('/start')).toBe(false);
    expect(ownerNeedsState('nima gap')).toBe(true);
    expect(ownerReply('/start', null).text).toContain('/kassa');
  });

  it('builds a report from a raw admin snapshot', () => {
    const state = JSON.parse(JSON.stringify(emptyState()));
    const raw = { actor: { id: 'a', name: 'Egasi', role: 'admin', companyId: state.companyId }, state };
    expect(ownerNeedsState('/kassa')).toBe(true);
    expect(ownerReply('nima gap', raw).text).toContain('tanilmadi');
    const answer = ownerReply('/kassa', raw);
    expect(answer.text).toContain('Kassa holati');
    expect(answer.keyboard).toEqual(ownerKeyboard());
  });

  it('every keyboard button is a known command label', () => {
    const labels = OWNER_COMMANDS.map(row => row.label);
    expect(ownerKeyboard().flat().sort()).toEqual([...labels].sort());
  });

  it('the bundle shipped to the Edge Function matches the source', async () => {
    const result = await build({
      entryPoints: ['src/telegram-owner.ts'], bundle: true, format: 'esm', target: 'es2022', platform: 'neutral',
      charset: 'utf8', legalComments: 'none', write: false,
      banner: { js: '// GENERATED by `npm run build:bot` from src/telegram-owner.ts — do not edit by hand.' },
    });
    const committed = readFileSync('supabase/functions/_shared/owner-bot.generated.js', 'utf8');
    expect(committed.replace(/\r\n/g, '\n')).toBe(result.outputFiles[0].text);
  });
});
