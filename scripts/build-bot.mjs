// Bundles the pure owner-bot logic (src/telegram-owner.ts and the domain code it reuses)
// into one ESM file the Deno Edge Function can import. Run: npm run build:bot
import { build } from 'esbuild';

await build({
  entryPoints: ['src/telegram-owner.ts'],
  outfile: 'supabase/functions/_shared/owner-bot.generated.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: '// GENERATED by `npm run build:bot` from src/telegram-owner.ts — do not edit by hand.' },
});
console.log('owner-bot.generated.js built');
